function docs(list: [name: string, filedDaysAgo: number | null, required?: boolean][]): ClaimDocument[] {
  return list.map(([name, ago, required = true]) => ({
    name,
    required,
    filedAt: ago === null ? undefined : wd(-ago),
    evidence: ago === null ? undefined : `${name}.pdf`,
  }));
}

